  const orderTable = order ? `<div class="section-heading"><h3>Stock order</h3><span>${bySection.size} sections${specials.length ? ` · ${specials.length} special length${specials.length > 1 ? 's' : ''}` : ''}</span></div><table class="fastener-table"><thead><tr><th>Section</th><th>Bars</th><th class="num">kg</th></tr></thead><tbody>${order}</tbody></table>` : '';
  const fasteners = data.fasteners.map(fastener => `<tr><td>${esc(fastener.description)}</td><td class="num">${fastener.qty}</td></tr>`).join('');
  $('#procurement-content').innerHTML = `<div class="summary-strip"><div class="summary-box"><span>Stock bars</span><strong>${data.cut_list.length}</strong></div><div class="summary-box"><span>Total offcut</span><strong>${fmt(totalOffcut / 1000)} m</strong></div>${wasteBox}<div class="summary-box"><span>Order quantity</span><strong>${fmt(data.summary.order_t)} t</strong></div></div>${orderTable}<div class="section-heading"><h3>Cutting list</h3><span>Least bar bought from the stock lengths · drawn to scale</span></div><div class="cut-grid">${bars}</div><div class="section-heading"><h3>Fasteners</h3><span>${data.fasteners.length} item types</span></div><table class="fastener-table"><thead><tr><th>Description</th><th class="num">Quantity</th></tr></thead><tbody>${fasteners}</tbody></table>`;
